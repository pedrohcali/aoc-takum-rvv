#!/usr/bin/env python3
"""Static decoder analysis: value classes of every bit pattern per format.

For each IEEE format (E4M3, E5M2, binary16, bfloat16, binary32) and each
takum width it counts the patterns that decode to zero, subnormals,
infinities, NaN/NaR and normal values, and records the decoder parameters:
the exponent field width and how many leading bits determine the exponent.

8- and 16-bit formats are enumerated exhaustively through the decoders in
takum/ieee.py and takum/codec.py. 32-bit formats use closed formulas, which
the script first checks against the exhaustive counts of the smaller formats.

Outputs results/isa-encodings.csv and results/isa-macros.tex.
"""
import csv
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from takum.codec import TakumFormat, power_of_two  # noqa: E402
from takum.ieee import E4M3, E5M2, FP16, FP32, IEEEFormat, is_finite  # noqa: E402

BF16 = IEEEFormat("BF16", 8, 7)  # only for this analysis; not a benchmark format
WORDS = {"E4M3": "EFourMThree", "E5M2": "EFiveMTwo", "FP16": "FPSixteen", "BF16": "BFSixteen",
         "FP32": "FPThirtyTwo", "T8": "TEight", "T16": "TSixteen", "T32": "TThirtyTwo"}
CLASSES = ("zero", "subnormal", "infinite", "nan", "normal")


def ieee_exhaustive(fmt: IEEEFormat) -> dict:
    counts = dict.fromkeys(CLASSES, 0)
    smallest_normal = power_of_two(fmt.emin)
    for bits in range(1 << fmt.width):
        value = fmt.decode(bits)
        if not is_finite(value):
            counts["nan" if value != value else "infinite"] += 1
        elif value == 0:
            counts["zero"] += 1
        elif abs(value) < smallest_normal:
            counts["subnormal"] += 1
        else:
            counts["normal"] += 1
    return counts


def ieee_formula(fmt: IEEEFormat) -> dict:
    fractions = (1 << fmt.man_bits) - 1
    if fmt.ofp8_e4m3:
        infinite, nan = 0, 2
    else:
        infinite, nan = 2, 2 * fractions
    counts = {"zero": 2, "subnormal": 2 * fractions, "infinite": infinite, "nan": nan}
    counts["normal"] = (1 << fmt.width) - sum(counts.values())
    return counts


def takum_exhaustive(width: int) -> dict:
    fmt = TakumFormat(width)
    counts = dict.fromkeys(CLASSES, 0)
    for bits in range(1 << width):
        value = fmt.decode(bits)
        counts["nan" if value is None else "zero" if value == 0 else "normal"] += 1
    return counts


def takum_formula(width: int) -> dict:
    return {"zero": 1, "subnormal": 0, "infinite": 0, "nan": 1, "normal": (1 << width) - 2}


def main():
    for fmt in (E4M3, E5M2, FP16, BF16):
        assert ieee_exhaustive(fmt) == ieee_formula(fmt), fmt.name
    for width in (8, 16):
        assert takum_exhaustive(width) == takum_formula(width), width
    rows = []
    for fmt in (E4M3, E5M2, FP16, BF16, FP32):
        counts = ieee_formula(fmt)
        rows.append({"format": fmt.name, "width": fmt.width, "exponent_field_bits": fmt.exp_bits,
                     "fraction_bits": fmt.man_bits, "exponent_from_leading_bits": 1 + fmt.exp_bits,
                     **counts})
    for width in (8, 16, 32):
        counts = takum_formula(width)
        # S, D, three regime bits and at most seven characteristic bits.
        rows.append({"format": f"T{width}", "width": width, "exponent_field_bits": "3+0..7",
                     "fraction_bits": f"{max(0, width - 12)}..{width - 5}",
                     "exponent_from_leading_bits": 12, **counts})
    out = ROOT / "results"
    with (out / "isa-encodings.csv").open("w", newline="") as file:
        writer = csv.DictWriter(file, list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    lines = ["% Generated by scripts/isa_analysis.py"]
    for r in rows:
        w = WORDS[r["format"]]
        special = r["zero"] + r["subnormal"] + r["infinite"] + r["nan"]
        share = 100 * special / (1 << r["width"])
        lines += [f"\\newcommand{{\\IsaZero{w}}}{{{r['zero']:,}}}".replace(",", "{,}"),
                  f"\\newcommand{{\\IsaSub{w}}}{{{r['subnormal']:,}}}".replace(",", "{,}"),
                  f"\\newcommand{{\\IsaInf{w}}}{{{r['infinite']:,}}}".replace(",", "{,}"),
                  f"\\newcommand{{\\IsaNaN{w}}}{{{r['nan']:,}}}".replace(",", "{,}"),
                  f"\\newcommand{{\\IsaSpecial{w}}}{{{share:.{1 if share >= 0.1 else 3}f}}}"]
    (out / "isa-macros.tex").write_text("\n".join(lines) + "\n")
    for r in rows:
        print(r)


if __name__ == "__main__":
    main()
